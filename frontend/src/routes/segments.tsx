import { createFileRoute } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { PieChart } from "lucide-react";
import { EmptyState, ErrorState, KeyValueGrid, PageHeader, Panel } from "@/components/common";
import { api, ApiError, describeError, isApiConfigured } from "@/lib/api";
import { pageMeta } from "@/lib/seo";

export const Route = createFileRoute("/segments")({
  head: () => pageMeta("Segmentation", "Customer segments generated by the clustering model."),
  component: Segments,
});

function Segments() {
  const q = useQuery({ queryKey: ["segments"], queryFn: ({ signal }) => api.segments(signal), enabled: isApiConfigured, retry: false });
  const notReady = !isApiConfigured || (q.error instanceof ApiError && q.error.status === 503);
  return (
    <>
      <PageHeader eyebrow="Segments" title="Customer Segmentation" description="Display only segments returned by the clustering API. No fabricated segment assignments." />
      {notReady ? (
        <EmptyState icon={<PieChart />} title="Clustering Model Not Connected">The clustering model is not available yet. Segment details will appear when the API provides them.</EmptyState>
      ) : q.isError ? (
        <ErrorState message={describeError(q.error)} onRetry={() => q.refetch()} retrying={q.isFetching} />
      ) : q.isLoading ? (
        <div className="h-48 animate-pulse rounded-2xl bg-muted" />
      ) : (
        <div className="grid gap-5 md:grid-cols-2">
          {(Array.isArray(q.data) ? q.data : [q.data ?? {}]).map((s, i) => (
            <Panel key={i} title={String((s as Record<string, unknown>).name ?? `Cluster ${i + 1}`)}><KeyValueGrid data={s as Record<string, unknown>} /></Panel>
          ))}
        </div>
      )}
    </>
  );
}